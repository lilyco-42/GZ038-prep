#ifndef __BOARD_H__
#define __BOARD_H__

/*============================================================================
 * board.h  蓝色 ZigBee 节点盒 板级支持包(BSP)头文件
 *----------------------------------------------------------------------------
 * 适用平台: 新大陆物联网竞赛平台 蓝色 ZigBee 节点盒(CC2530 系列 SoC)
 * 说明:
 *   本头文件只做"引脚/定时器/按键"抽象, 与具体芯片寄存器解耦。
 *   移植到真实工程时, 把下方三个 BSP 函数在对应的 bsp 源文件里
 *   用寄存器操作实现即可, main.c 的业务逻辑无需改动。
 *
 * 硬件连线(以节点盒丝印为准):
 *   LED1  -> P1_0  (低电平点亮 / 高电平熄灭, 按本板共阳接法)
 *   LED2  -> P1_1  (同上)
 *   SW1   -> P0_1  (按下为低电平, 内部上拉)
 *   呼吸灯由定时器中断改变 PWM 占空比实现(CC2530 用 T1 定时器)
 *===========================================================================*/

/*------------------------- 引脚定义(按节点盒实际丝印修改) ------------------*/
#define LED1_GPIO_DIR    P1DIR
#define LED1_GPIO_SET    P1_0        /* LED1 控制脚 */
#define LED2_GPIO_SET    P1_1        /* LED2 控制脚 */

#define SW1_GPIO_DIR     P0DIR
#define SW1_GPIO         P0_1        /* SW1 按键脚, 按下=0 */

/* 板上 LED 为共阳接法: 输出 0 点亮, 输出 1 熄灭 */
#define LED1_ON()        (LED1_GPIO_SET = 0)
#define LED1_OFF()       (LED1_GPIO_SET = 1)
#define LED2_ON()        (LED2_GPIO_SET = 0)
#define LED2_OFF()       (LED2_GPIO_SET = 1)

/*------------------------- 按键消抖与时序参数(单位 ms) --------------------*/
#define KEY_SCAN_PERIOD_MS     5     /* 按键扫描周期(放在 5ms 定时中断里调用) */
#define KEY_LONG_PRESS_MS      1500  /* 判定为"长按"的按下时长阈值 */
#define KEY_DOUBLE_GAP_MS      400   /* 两次按下间隔小于该值判定为"双击" */

/*------------------------- 呼吸灯参数 --------------------------------------*/
#define BREATH_PERIOD_MS       5     /* PWM 刷新周期 */
#define BREATH_LEVEL_MAX       100   /* 亮度等级 0~100 */
#define BREATH_STEP_MS         20    /* 每 20ms 亮度变化一次, 调节呼吸快慢 */

/*============================================================================
 * 对外提供的 BSP 接口(在 bsp.c 中用寄存器实现)
 *==========================================================================*/
void  Board_Init(void);              /* 时钟/IO方向/上拉/定时器初始化 */
unsigned char Key_SW1_Down(void);    /* 返回 1 表示 SW1 当前按下(低电平) */
void  PWM_SetDuty(unsigned char duty); /* 设置 LED1 PWM 占空比 0~100, 用于呼吸灯 */

#endif /* __BOARD_H__ */
