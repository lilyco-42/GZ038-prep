/*****************************************************************************
 * 文件名称 : main.c (板A —— 无线通讯控制【发送端】)
 * 所属任务 : GZ038 第4套 模块二 子任务2-2 设备无线通讯控制系统
 * 功能描述 :
 *   本板为两块黑色 ZigBee 开发板中的【A 板】, 贴"板A"标签。
 *   板A 上电后初始化 UART(串口)与 ZigBee 模块, 循环扫描按键 SW1。
 *   每按一次 SW1, 通过 ZigBee 无线链路向【板B】发送一帧"风扇开关切换"命令,
 *   板B 收到命令后控制继电器, 从而远程启停板B 所接的风扇。
 *
 * 通讯协议(自定义, 两板约定一致):
 *   帧头1  帧头2  命令字  校验和
 *   0xAA   0x55   CMD      SUM
 *   其中 SUM = 0xAA + 0x55 + CMD, 只取低 8 位。
 *   CMD = 0x01 表示"风扇状态翻转一次"(启动/停止交替)。
 *
 * 硬件约定(以本赛项黑色 ZigBee 开发板原理图为准, 若引脚不同请改这里):
 *   - SW1 按键        : P0_1  (按下为低电平, 内部上拉)
 *   - ZigBee 模块串口 : UART0 (TX=P0_3, RX=P0_2), 波特率 9600, 8N1
 *   - 板A 上 1 个 LED : P1_0  (用于指示"已按下并发送", 闪烁提示)
 *
 * 说明: 本工程不依赖特定 SDK, 采用寄存器级写法, 便于在 CC2530/IAR
 *       或同等 Cortex-M 开发环境中按板级头文件替换宏后编译。
 ****************************************************************************/

#include "main.h"

/* 自定义无线帧命令字 */
#define FRAME_HEAD1    0xAAu   /* 帧头第一字节 */
#define FRAME_HEAD2    0x55u   /* 帧头第二字节 */
#define CMD_FAN_TOGGLE 0x01u   /* 风扇开关翻转命令 */

/* 发送状态指示 LED 翻转次数, 用于按键反馈 */
static uint8 led_tick = 0;

/*---------------------------------------------------------------------------
 * 函数: void BoardA_Init(void)
 * 描述: 板A 初始化 —— 系统时钟、按键 GPIO、LED GPIO、串口。
 *---------------------------------------------------------------------------*/
void BoardA_Init(void)
{
    SystemClock_Init();        /* 系统时钟初始化(板级) */
    Key_Init();                /* SW1 按键引脚 P0_1, 输入上拉 */
    Led_Init();                /* 指示灯引脚 P1_0, 输出, 默认灭 */
    Uart0_Init(9600);          /* ZigBee 透传串口, 9600bps */
}

/*---------------------------------------------------------------------------
 * 函数: void ZigBee_SendFanToggle(void)
 * 描述: 组帧并通过 ZigBee 串口发送"风扇翻转"命令。
 *---------------------------------------------------------------------------*/
void ZigBee_SendFanToggle(void)
{
    uint8 sum = FRAME_HEAD1 + FRAME_HEAD2 + CMD_FAN_TOGGLE;

    Uart0_SendByte(FRAME_HEAD1);     /* 帧头1 */
    Uart0_SendByte(FRAME_HEAD2);     /* 帧头2 */
    Uart0_SendByte(CMD_FAN_TOGGLE);  /* 命令字: 风扇翻转 */
    Uart0_SendByte(sum);             /* 校验和 */
}

/*---------------------------------------------------------------------------
 * 函数: void Key_ScanTask(void)
 * 描述: 扫描 SW1 按键, 软件消抖; 每按一次发送一帧风扇翻转命令,
 *       并让指示灯翻转一次作为发送成功的本地反馈。
 *---------------------------------------------------------------------------*/
void Key_ScanTask(void)
{
    /* 检测到按键按下(低电平) */
    if (Key_SW1_Pressed() == 0)
    {
        Delay_ms(20);                          /* 消抖延时 */
        if (Key_SW1_Pressed() == 0)            /* 再次确认仍为按下 */
        {
            ZigBee_SendFanToggle();            /* 发送无线控制帧 */
            Led_Toggle();                      /* 板A 指示灯翻转反馈 */

            /* 等待按键释放, 避免连发 */
            while (Key_SW1_Pressed() == 0)
            {
                Delay_ms(1);
            }
            Delay_ms(20);                      /* 释放消抖 */
        }
    }
}

/*---------------------------------------------------------------------------
 * 主函数
 *---------------------------------------------------------------------------*/
void main(void)
{
    BoardA_Init();

    while (1)
    {
        Key_ScanTask();     /* 循环扫描按键 */
        Delay_ms(10);       /* 降低扫描负载 */
    }
}
