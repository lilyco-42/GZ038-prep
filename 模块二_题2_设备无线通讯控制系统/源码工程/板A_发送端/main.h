#ifndef __MAIN_H__
#define __MAIN_H__

/* 基本类型重定义(若工程已有 stdint.h 可直接使用) */
typedef unsigned char  uint8;
typedef unsigned short uint16;
typedef unsigned int   uint32;

/*---------------------------------------------------------------------------
 * 板级初始化与延时
 *---------------------------------------------------------------------------*/
void SystemClock_Init(void);     /* 系统时钟 */
void Delay_ms(uint16 ms);        /* 毫秒延时 */

/*---------------------------------------------------------------------------
 * 按键 SW1 (P0_1): 按下为低电平
 *---------------------------------------------------------------------------*/
void Key_Init(void);             /* 配置为带上拉输入 */
uint8 Key_SW1_Pressed(void);     /* 返回 0=按下, 1=松开 */

/*---------------------------------------------------------------------------
 * 板A 指示灯 (P1_0)
 *---------------------------------------------------------------------------*/
void Led_Init(void);
void Led_Toggle(void);

/*---------------------------------------------------------------------------
 * UART0 (连接 ZigBee 透传模块)
 *---------------------------------------------------------------------------*/
void Uart0_Init(uint32 baud);           /* 初始化串口 */
void Uart0_SendByte(uint8 byte);        /* 阻塞发送 1 字节 */

#endif /* __MAIN_H__ */
