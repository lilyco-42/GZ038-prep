/****************************************************************************
 * 子任务2-2  ZigBee 按键控制程序（蓝色 ZigBee 节点盒）
 *--------------------------------------------------------------------------*
 * 平台: CC2530（TI ZigBee SoC，Z-Stack 风格裸机 main.c，可直接放入 IAR /
 *       SmartRF 工程的 ZMain 或 App 层编译烧写）。
 *
 * 赛题要求（严格按任务书实现）：
 *   1. 程序通电，节点盒的 LED1、LED2 灯都不亮。
 *   2. 长按（按住不松开）SW1 键：LED1 灯亮，LED2 灯熄灭。
 *   3. 松开 SW1 键：LED1、LED2 都常亮。
 *
 * 实现思路：
 *   - 初始化时把 LED1/LED2 对应的 GPIO 配置为推挽输出，并全部置“灭”。
 *   - 主循环以约 10ms 周期扫描 SW1 按键（带软件消抖）。
 *   - 用“按下保持态”和“松开沿”两个状态量做边沿检测：
 *       * 只要 SW1 处于按下（按住不放）状态  -> LED1 亮、LED2 灭；
 *       * 一旦检测到 SW1 由按下变为松开（释放边沿） -> LED1、LED2 全部常亮。
 *   - 该逻辑天然满足“长按不松时 LED1 亮 LED2 灭，松手后两灯常亮”。
 *
 * 板级引脚（蓝色 ZigBee 节点盒，新大陆竞赛工位常用默认接线；
 * 若实际工位丝印不同，仅需修改下方 4 个宏即可，业务逻辑无需改动）：
 *   LED1  -> P1_0   (低电平点亮 / 高电平熄灭，本板为共阳：输出 0 亮)
 *   LED2  -> P1_1   (同上)
 *   SW1   -> P0_1   (内部上拉，按下接地 -> 读到 0；松开 -> 读到 1)
 *--------------------------------------------------------------------------*
 * 注意：CC2530 寄存器头文件 <ioCC2530.h> 由 TI IAR 安装包提供。
 ****************************************************************************/

#include <ioCC2530.h>

/*------------------------- 板级引脚宏（按实际工位修改） ------------------*/
#define   LED1_PIN        P1_0          /* LED1 控制脚 */
#define   LED2_PIN        P1_1          /* LED2 控制脚 */
#define   SW1_PIN         P0_1          /* SW1 按键输入脚 */

/* 本板 LED 为共阳接法：IO 输出 0 点亮，输出 1 熄灭。
   若你的板子是共阴（输出 1 点亮），把下面两个宏对调即可。 */
#define   LED_ON()        do { LED1_PIN = 0;  } while(0)   /* 仅点亮 LED1 */
#define   LED1_ON()       do { LED1_PIN = 0;  } while(0)
#define   LED2_OFF()      do { LED2_PIN = 1;  } while(0)
#define   LED1_OFF()      do { LED1_PIN = 1;  } while(0)
#define   LED_BOTH_ON()   do { LED1_PIN = 0; LED2_PIN = 0; } while(0) /* 两灯常亮 */
#define   LED_BOTH_OFF()  do { LED1_PIN = 1; LED2_PIN = 1; } while(0) /* 两灯全灭 */

/* 按键电平：按下为低电平（接地） */
#define   SW1_PRESSED()   (SW1_PIN == 0)

/* 消抖计数：主循环约 10ms 跑一圈，连续读到 N 次稳定电平才认为有效 */
#define   KEY_DEBOUNCE_CNT   3

/*--------------------------------------------------------------------------*
 * 函数：Key_Scan()
 * 功能：扫描 SW1 并做消抖，返回消抖后的稳定按键电平。
 *   返回 1 -> 按键松开；返回 0 -> 按键按下。
 * 说明：每次调用都推进一次消抖状态，需以固定周期(约10ms)循环调用。
 *--------------------------------------------------------------------------*/
static unsigned char Key_Scan(void)
{
    static unsigned char s_cnt = 0;
    static unsigned char s_last_level = 1;   /* 初始默认松开 */

    unsigned char cur = (SW1_PRESSED() == 0) ? 0 : 1;

    if (cur == s_last_level)
    {
        s_cnt = 0;                            /* 电平稳定，保持当前判定 */
    }
    else
    {
        s_cnt++;                              /* 电平变化，开始计数消抖 */
        if (s_cnt >= KEY_DEBOUNCE_CNT)
        {
            s_cnt = 0;
            s_last_level = cur;               /* 连续 N 次一致，确认新电平 */
        }
    }
    return s_last_level;
}

/*--------------------------------------------------------------------------*
 * 函数：Delay_ms()
 * 功能：粗约毫秒级延时（16MHz 系统时钟下近似），仅用于上电与消抖节拍。
 *--------------------------------------------------------------------------*/
static void Delay_ms(unsigned int ms)
{
    unsigned int i, j;
    for (i = 0; i < ms; i++)
    {
        for (j = 0; j < 535; j++)
        {
            /* 空循环占位，CC2530 16MHz 下约 1ms */
        }
    }
}

/*--------------------------------------------------------------------------*
 * 主函数
 *--------------------------------------------------------------------------*/
void main(void)
{
    unsigned char key_level;        /* 当前消抖后按键电平：0=按下, 1=松开 */
    unsigned char last_level = 1;   /* 上一拍按键电平，用于检测“释放沿” */

    /* ---- 1. 硬件初始化 ---- */
    /* LED1/LED2 设为通用 IO 功能，方向为输出 */
    P1SEL &= ~(1 << 0);             /* P1_0 设为 GPIO */
    P1DIR |=  (1 << 0);             /* P1_0 输出 */
    P1SEL &= ~(1 << 1);             /* P1_1 设为 GPIO */
    P1DIR |=  (1 << 1);             /* P1_1 输出 */

    /* SW1(P0_1) 设为输入，使能内部上拉 */
    P0SEL &= ~(1 << 1);             /* P0_1 设为 GPIO */
    P0DIR &= ~(1 << 1);             /* P0_1 输入 */
    P0INP &= ~(1 << 1);             /* 接上拉（非三态） */
    P2INP &= ~(1 << 7);             /* P0 口上拉/下拉选择：上拉 */

    /* ---- 2. 上电默认：LED1、LED2 都不亮（赛题第1条） ---- */
    LED_BOTH_OFF();

    /* ---- 3. 主循环：按键扫描 + 状态机 ---- */
    while (1)
    {
        key_level = Key_Scan();     /* 0=按住, 1=松开 */

        if (key_level == 0)
        {
            /* 正在按住 SW1（长按不松开）：LED1 亮，LED2 灭（赛题第2条） */
            LED1_ON();
            LED2_OFF();
        }
        else
        {
            /* 当前是松开态 */
            if (last_level == 0)
            {
                /* 检测到“按住 -> 松开”的释放沿：松开 SW1，
                   LED1、LED2 全部常亮（赛题第3条） */
                LED_BOTH_ON();
            }
            /* 已经松开过且两灯已常亮，则保持常亮，不再改动 */
        }

        last_level = key_level;
        Delay_ms(10);               /* 约 10ms 扫描周期，兼顾消抖与响应 */
    }
}
