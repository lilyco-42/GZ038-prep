#ifndef __BOARD_H__
#define __BOARD_H__
/**************************************************************************
 * 文件名: board.h
 * 说  明: GZ038 第5套 子任务2-2 密码输入反馈模块 —— 黑色 ZigBee(CC2530)核心板引脚定义
 *        如实际工位板引脚与下表不符，仅需修改本文件宏定义，main.c 无需改动。
 * 平台: CC2530 (8051内核) + IAR EW8051
 **************************************************************************/
#include <ioCC2530.h>

/* ---------- 板载 4 颗指示灯 D4/D3/D6/D5，低电平点亮(0=亮,1=灭) ---------- */
/* 赛题要求: D4、D3、D6、D5 从左到右分别代表密码某一位二进制的高位到低位 */
#define D4   P1_0     /* 密码位 B3(最高位) */
#define D3   P1_1     /* 密码位 B2         */
#define D6   P1_2     /* 密码位 B1         */
#define D5   P1_3     /* 密码位 B0(最低位) */

/* ---------- 按键: 内部上拉输入，按下为低电平 ---------- */
#define SW1  P0_1     /* 密码翻页按键(每按一次显示下一位) */
#define SW2  P0_2     /* 复位按键: 板灯全亮、外接灯泡灭  */

/* ---------- 外接灯泡继电器: 高电平点亮(1=亮,0=灭) ---------- */
#define BULB P1_4

/* 按键电平常量 */
#define KEY_DOWN   0
#define KEY_UP     1

#endif /* __BOARD_H__ */
