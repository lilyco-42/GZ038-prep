/**************************************************************************
 * 文件名: main.c
 * 说  明: GZ038 第5套 子任务2-2 密码输入反馈模块
 * 平  台: CC2530 黑色 ZigBee 核心板 (IAR EW8051, main.c + board.h)
 *
 * 赛题要求回顾:
 *   1) 解密密码为 C639(从左到右共 4 位)，用板上 4 颗灯 D4/D3/D6/D5
 *      从左到右分别表示该位二进制的高位~低位，1 亮 0 灭；
 *   2) 程序开始运行: D4、D3、D6、D5 全亮；
 *   3) 第 1 次按 SW1 -> 显示第 1 位密码 C(1100)；
 *      第 2 次按 SW1 -> 显示第 2 位密码 6(0110)；
 *      第 3 次按 SW1 -> 显示第 3 位密码 3(0011)；
 *      第 4 次按 SW1 -> 显示第 4 位密码 9(1001)，同时打开外接灯泡；
 *   4) 按 SW2 -> 板灯复位全亮，外接灯泡灭；
 *   5) 以上步骤可重复；
 *   6) 必须使用定时器(本工程用 Timer1 1ms 节拍)实现按键消抖与灯/灯泡控制。
 *
 * 密码二进制对照表(1=亮,0=灭):
 *   第1位 C = 1100 -> D4亮 D3亮 D6灭 D5灭
 *   第2位 6 = 0110 -> D4灭 D3亮 D6亮 D5灭
 *   第3位 3 = 0011 -> D4灭 D3灭 D6亮 D5亮
 *   第4位 9 = 1001 -> D4亮 D3灭 D6灭 D5亮
 **************************************************************************/
#include <ioCC2530.h>
#include "board.h"

/* ============================ 全局变量 ================================= */
static volatile unsigned short g_tickMs = 0;   /* 1ms 节拍计数器 */

/* 密码表: C639，每个数字用 4 位二进制表示(高->低对应 D4..D5) */
static const unsigned char CODE_TABLE[4] = {0xC, 0x6, 0x3, 0x9};

static unsigned char g_step = 0;   /* 已成功按下 SW1 的次数 0~4 */

/* 按键消抖状态 */
static unsigned char  key1Stable = KEY_UP;
static unsigned short key1Cnt    = 0;
static unsigned char  key2Stable = KEY_UP;
static unsigned short key2Cnt    = 0;
#define DEBOUNCE_MS   20           /* 消抖时间 20ms */

/* ============================ 函数声明 ================================ */
static void  Port_Init(void);
static void  Timer1_Init(void);
static void  Leds_AllOn(void);
static void  Leds_ShowDigit(unsigned char step);
static void  Bulb_On(void);
static void  Bulb_Off(void);
static void  Keys_Scan(void);

/**************************************************************************
 * 端口初始化: LED/继电器为输出，按键为上拉输入
 **************************************************************************/
static void Port_Init(void)
{
  /* P1.0~P1.3 接 D4/D3/D6/D5，P1.4 接外接灯泡继电器 -> 全部推挽输出 */
  P1DIR |= 0x1F;
  P1SEL &= ~0x1F;

  /* P0.1(SW1)、P0.2(SW2) -> 输入并使能上拉 */
  P0DIR &= ~0x06;
  P0INP &= ~0x06;
  P2INP &= ~0x20;     /* 上拉/下拉选择: P0 上拉 */

  /* 初始状态: 4 颗板灯全亮(低电平点亮)，外接灯泡灭 */
  Leds_AllOn();
  Bulb_Off();
}

/**************************************************************************
 * Timer1 初始化: 1ms 定时中断，提供系统节拍(用于消抖与灯控)
 * 系统时钟取 32MHz, Timer1 采用 32 分频 -> 1us/tick, 1000 计数 = 1ms
 **************************************************************************/
static void Timer1_Init(void)
{
  T1CTL = 0x0D;       /* 分频 /32, 模模式; 从 0 计数到终值后中断重装 */
  T1CCTL0 = 0x44;     /* 通道0: 比较模式, 输出比较中断 */
  T1CC0 = 1000;       /* 1000 * 1us = 1ms */
  T1IE = 1;           /* 允许 Timer1 中断 */
  EA = 1;             /* 开总中断 */
}

/**************************************************************************
 * Timer1 中断服务函数: 每 1ms 进一次，仅维护节拍计数
 **************************************************************************/
void Timer1_ISR(void) __interrupt T1_VECTOR
{
  T1CTL &= ~0x01;     /* 清溢出标志 */
  if (g_tickMs < 0xFFFF) g_tickMs++;
}

/**************************************************************************
 * 4 颗板灯全亮(复位/初始状态)
 **************************************************************************/
static void Leds_AllOn(void)
{
  /* 低电平点亮 -> 全写 0 */
  D4 = 0; D3 = 0; D6 = 0; D5 = 0;
}

/**************************************************************************
 * 按当前步骤刷新 4 颗板灯显示
 *   step = 1..4 : 显示第 step 位密码
 *   step = 0    : 未开始(初始/复位)，全亮
 **************************************************************************/
static void Leds_ShowDigit(unsigned char step)
{
  unsigned char v;
  if (step == 0) { Leds_AllOn(); return; }
  if (step > 4)  step = 4;

  v = CODE_TABLE[step - 1];     /* 取该位的 4 位二进制值 */
  /* 灯为低电平点亮: 位=1(亮) -> 输出 0; 位=0(灭) -> 输出 1 */
  D4 = (((v >> 3) & 0x01) == 1) ? 0 : 1;   /* 最高位 -> D4 */
  D3 = (((v >> 2) & 0x01) == 1) ? 0 : 1;
  D6 = (((v >> 1) & 0x01) == 1) ? 0 : 1;
  D5 = (((v     ) & 0x01) == 1) ? 0 : 1;   /* 最低位 -> D5 */
}

static void Bulb_On(void)  { BULB = 1; }
static void Bulb_Off(void) { BULB = 0; }

/**************************************************************************
 * 按键扫描(非阻塞，由主循环调用，消抖时间由 Timer1 节拍保证)
 *   SW1 下降沿(按下一次) -> g_step++，并刷新对应位密码；
 *      第 4 次按下时同时打开外接灯泡；
 *   SW2 下降沿(按下一次) -> 复位: g_step=0，板灯全亮，灯泡灭。
 **************************************************************************/
static void Keys_Scan(void)
{
  unsigned char raw1 = SW1;
  unsigned char raw2 = SW2;

  /* ---- SW1 消抖 ---- */
  if (raw1 != key1Stable) {
    if (++key1Cnt >= DEBOUNCE_MS) {
      key1Cnt = 0;
      if (raw1 == KEY_DOWN && key1Stable == KEY_UP) {
        /* 确认按下一次 */
        if (g_step < 4) g_step++;
        Leds_ShowDigit(g_step);
        if (g_step == 4) Bulb_On();    /* 第 4 次按下: 显示第 4 位并开灯 */
      }
      key1Stable = raw1;
    }
  } else {
    key1Cnt = 0;
  }

  /* ---- SW2 消抖 ---- */
  if (raw2 != key2Stable) {
    if (++key2Cnt >= DEBOUNCE_MS) {
      key2Cnt = 0;
      if (raw2 == KEY_DOWN && key2Stable == KEY_UP) {
        /* 确认按下一次 -> 复位，可重复执行 */
        g_step = 0;
        Leds_AllOn();
        Bulb_Off();
      }
      key2Stable = raw2;
    }
  } else {
    key2Cnt = 0;
  }
}

/**************************************************************************
 * 主函数
 **************************************************************************/
void main(void)
{
  Port_Init();
  Timer1_Init();

  /* 启动即显示初始状态: 4 颗板灯全亮，外接灯泡灭 */
  g_step = 0;
  Leds_AllOn();
  Bulb_Off();

  while (1) {
    Keys_Scan();          /* 非阻塞按键扫描(1ms 节拍消抖) */
    /* 此处可插入低功耗/其他任务; 灯与灯泡状态由状态机决定，无需重复刷新 */
  }
}
