#ifndef __BOARD_H__
#define __BOARD_H__
/**************************************************************************
 * 文件名: board.h
 * 说  明: GZ038 第9套 子任务2-2 CC2530 串口通讯系统 —— 黑色 ZigBee(CC2530)
 *        核心板引脚定义。如实际工位板引脚/波特率与下表不符, 仅需修改本文件,
 *        main.c 无需改动。
 * 平台: CC2530 (8051内核) + IAR EW8051
 **************************************************************************/
#include <ioCC2530.h>

/* ---------- 板载 4 颗指示灯 D4/D3/D6/D5, 低电平点亮(0=亮,1=灭) ---------- */
/* 赛题灯位绑定(指令字节): b3->D4  b2->D3  b1->D6  b0->D5              */
#define D4   P1_0     /* 指令字节 b3 (位序1) */
#define D3   P1_1     /* 指令字节 b2 (位序2) */
#define D6   P1_2     /* 指令字节 b1 (位序3) */
#define D5   P1_3     /* 指令字节 b0 (位序4) */

/* ---------- UART0: RX=P0.2, TX=P0.3 (DB9 -> 串口服务器COM3) ---------- */
/* 32MHz 系统时钟下 9600bps 的波特率寄存器取值(标准 CC2530 配置) */
#define BAUD_9600   59
#define BAUD_U0GCR  11

#endif /* __BOARD_H__ */
